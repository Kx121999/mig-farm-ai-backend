export function extendedKnowledgeReply(message,locale="ar",context={}){
  const t=n(message);
  if(!t) return null;
  for(const item of GLOSSARY){
    if(item.patterns.some(pattern=>t.includes(n(pattern)))){
      return {
        reply:pick(item.answers,`${context.sessionId||""}:${message}:${item.key}`),
        source:`human_knowledge_${item.key}`,
        confidence:"verified_or_safe_general",
        quick_replies:item.key==="first_time"?["طماطم","خيار","فلفل","أبغي مساعدة بالاختيار"]:[]
      };
    }
  }

  if(/(ساعدوني اختار|ساعدني اختار|مساعده في الاختيار|مساعدة في الاختيار|تساعدون بالاختيار|help me choose)/.test(t)){
    return {
      reply:"أكيد. ما بعطيك قائمة عشوائية؛ قل لي نوع الشي اللي تدور عليه أو المحصول، وبعدها أسألك معلومة واحدة كل مرة لحد ما نضيّق الاختيار.",
      source:"human_knowledge_selection_help",
      quick_replies:["بذور","أسمدة","مبيدات","ري"]
    };
  }

  if(/(كم صنف عندكم|عدد الاصناف|عدد الأصناف|كم منتج عندكم)/.test(t)){
    return {
      reply:"العدد يتغير مع المتجر والمخزون، فما أثبت رقم من الذاكرة. أقدر أبحث لك بالقسم أو المحصول وأعرض الموجود حاليًا.",
      source:"human_knowledge_dynamic_count"
    };
  }

  return null;
}

